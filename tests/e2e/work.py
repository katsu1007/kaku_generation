  ok(st['l']==[1],f'床の解体の行に部屋が入る（{st["l"]}）')
  pg.click('.wk-panel [data-wk=tab][data-v=new]');pg.wait_for_timeout(200)
  ok(pg.locator('.wk-panel [data-wkslot=fF]').count()==1 and pg.locator('.wk-panel [data-wkslot=fD]').count()==0,'新規のタブに切り替わる')
  pg.click('.wk-panel [data-wk=add]');pg.wait_for_timeout(300)
  pg.locator('.modal [data-list] [data-id]').first.click();pg.wait_for_timeout(400)
  ok(pg.locator('.wk-panel [data-wk=drop]').count()==1,'新規の項目を追加できる')
  pg.click('.wk-panel [data-wk=drop]');pg.wait_for_timeout(300)
  ok(pg.locator('.wk-panel [data-wk=drop]').count()==0,'追加した項目を外せる')
  ok(pg.locator('.wk-lines [data-line]').count()>=1,'下に工事の行が出る')
  # 床・壁・天井に分かれる・壁の下地に軽量がある・壁に足した物は壁の所に出る
  ok(pg.locator('.wk-panel .wk-sec').count()>=3,'床・壁・天井に分かれて出る')
  ok(pg.locator('.wk-panel [data-wkslot=wL] option[value=w-lgsW]').count()==1,'壁の下地（軽量）に軽鉄下地がある')
  pg.click('.wk-panel [data-wk=add][data-part=壁]');pg.wait_for_timeout(300);pg.fill('.modal [data-q]','ケイカル');pg.wait_for_timeout(200)
  pg.locator('.modal [data-list] [data-id]').first.click();pg.wait_for_timeout(400)
  sec=pg.evaluate("[...document.querySelectorAll('.wk-panel .wk-sec')].find(e=>e.querySelector('b').textContent==='壁').textContent")
  ok('ケイカル' in sec,'壁に足したケイカルが壁の所に出る')
  pg.select_option('.wk-panel [data-wkslot=wB]',index=2);pg.wait_for_timeout(400)
  ok('ケイカル' in pg.evaluate("[...document.querySelectorAll('.wk-panel .wk-sec')].find(e=>e.querySelector('b').textContent==='壁').textContent"),'ボードの下地を選んでも足したケイカルは消えない')
  ok(pg.evaluate("document.querySelector('#nextbar').classList.contains('nb-static')"),'③では次へが図面の上に浮かない')
  before=pg.evaluate("document.querySelector('.wk-panel b').textContent")
  pg.click('.wk-panel [data-wk=next]');pg.wait_for_timeout(500)
  after=pg.evaluate("document.querySelector('.wk-panel b').textContent")
  ok(after!=before and after.startswith('区画'),f'次の区画へで、まだの区画が選ばれる（{before}→{after}）')
  pg.click('.wk-panel [data-wk=clear]');pg.wait_for_timeout(200)
  pg.evaluate("document.querySelector('.wk-view').scrollIntoView({block:'center'})");pg.wait_for_timeout(200)
  pg.click('.wk-view [data-z=fit]');pg.wait_for_timeout(300)
  for k in range(1):
    xb=pg.evaluate("""(i)=>{const e=document.querySelector('.wk-view .faces polygon[data-i="'+i+'"]');const r=e.getBoundingClientRect();return [r.x+r.width/2,r.y+r.height/2]}""",bx[2])
    pg.mouse.click(xb[0],xb[1]);pg.wait_for_timeout(300)
  # 同じ大きさの区画も選ぶ（トイレのブース）
  pg.click('.wk-panel [data-wk=same]');pg.wait_for_timeout(300)
  n=pg.evaluate("document.querySelector('.wk-panel .muted').textContent")
  ok(not n.startswith('1 区画'),'同じ大きさの区画も選べる（%s）'%n)
  pg.click('.wk-panel [data-wk=tab][data-v=new]');pg.wait_for_timeout(200)
  sel=pg.locator('.wk-panel [data-wkslot=wF]');opt=sel.locator('option').nth(1).get_attribute('value');sel.select_option(opt);pg.wait_for_timeout(500)
  st=pg.evaluate("async()=>{const a=await import('./js/app.js');const p=a.state.projects.find(x=>x.id==='%s');return {n:p.rooms.length,w:p.lines.filter(l=>l.cat==='wall').map(l=>l.basis.rooms.length)}}"%pid)
  ok(st['w'] and st['w'][0]==st['n'] and st['n']>2,f'選んだ区画が全部部屋になって壁の仕上げに入る（{st}）')
  # 壁を1面ずつ
  pg.click('[data-wkm=wall]');pg.wait_for_timeout(400)
  seg=pg.evaluate("""async()=>{const a=await import('./js/app.js');const p=a.state.projects.find(x=>x.id==='%s');const r=p.rooms[0],f=p.drawing.plan.faces.find(f=>f.i===r.faces[0]);const q=f.poly;let b=null,bl=0;for(let k=0;k<q.length;k++){const u=q[k],v=q[(k+1)%%q.length],L=Math.hypot(v[0]-u[0],v[1]-u[1]);if(L>bl){bl=L;b=[(u[0]+v[0])/2,(u[1]+v[1])/2]}}return b}"""%pid)
  # 図面の座標を画面の座標に
  xy=pg.evaluate("""(b)=>{const s=document.querySelector('.wk-view svg.pv');const pt=s.createSVGPoint();pt.x=b[0];pt.y=-b[1];const m=s.querySelector('g').getScreenCTM();const r=pt.matrixTransform(m);return [r.x,r.y]}""",seg)
