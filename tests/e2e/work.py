  bx=pg.evaluate("""()=>{let best=null,ba=0;document.querySelectorAll('.wk-view .faces polygon').forEach(e=>{const r=e.getBoundingClientRect();if(r.width*r.height>ba&&r.width<300&&r.x>10&&r.right<innerWidth-60){ba=r.width*r.height;best=[r.x+r.width/2,r.y+r.height/2]}});return best}""")
