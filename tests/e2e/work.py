  ok(pg.locator('.wk-panel [data-wk=wadd]').count()==1,'壁の線をタップして選べる')
  pg.select_option('.wk-panel [data-wf=fin]',index=2);pg.click('.wk-panel [data-wk=wadd]');pg.wait_for_timeout(400)
  st=pg.evaluate("async()=>{const a=await import('./js/app.js');const p=a.state.projects.find(x=>x.id==='%s');return {w:(p.drawing.walls||[]).length,off:p.rooms.filter(r=>r.wallOff&&r.wallOff.fin>0).length,l:p.lines.filter(l=>l.fromDemo).length}}"%pid)
  ok(st['w']==1 and st['off']==1 and st['l']>=1,f'壁1面の仕上げが入り、部屋の壁から引かれる（{st}）')
  pg.click('.wk-panel [data-wk=wdel]');pg.wait_for_timeout(300)
  ok(pg.evaluate("async()=>{const a=await import('./js/app.js');return (a.state.projects.find(x=>x.id==='%s').drawing.walls||[]).length}"%pid)==0,'入れた壁を消せる')
